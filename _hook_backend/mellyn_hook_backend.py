"""
In-tree PEP 517 build backend for the Mellyn Guardrails pre-commit hooks (standard library only).

Why it exists: `language: python` hooks are the only kind pre-commit runs reliably on Windows, where
`#!/usr/bin/env python3` finds the Microsoft Store stub. pre-commit installs a `language: python` hook repository
with `pip install .` in a private virtualenv. This backend makes that work without adding a build dependency
(`requires = []`), so nothing is downloaded to build the hooks.

The wheel holds no copy of the scripts. It holds one launcher module and four console scripts. The launcher runs
the scripts from the source tree the wheel was built from: pre-commit's clone of this repository at the pinned
`rev`. The scripts therefore keep finding this pack's `.gitleaks.toml`, Semgrep rules and canonical agent rules
next to them, exactly as they do in CI. If that clone is deleted, the hooks fail closed and ask for
`pre-commit clean`.

Only `build_wheel` is supported. An sdist or editable install is refused.
"""

from __future__ import annotations

import base64
import hashlib
import zipfile
from pathlib import Path

NAME = "mellyn_guardrails_hooks"
VERSION = "1.0.0"
TAG = "py3-none-any"
# Fixed timestamp so the same source tree always builds byte-identical wheels.
ZIP_DATE = (1980, 1, 1, 0, 0, 0)

# console script -> script in scripts/
HOOKS: dict[str, str] = {
    "mellyn-verify-dependencies": "verify_dependencies.py",
    "mellyn-check-agent-rules": "sync_agent_rules.py",
    "mellyn-gitleaks": "precommit_gitleaks.py",
    "mellyn-semgrep": "precommit_semgrep.py",
}

_LAUNCHER = '''"""
Generated by mellyn_hook_backend.

Runs the Mellyn Guardrails hook scripts from the source tree this wheel was built from.
"""

import runpy
import sys
from pathlib import Path

SCRIPTS_DIR = Path({scripts_dir!r})


def _run(script: str) -> None:
    path = SCRIPTS_DIR / script
    if not path.is_file():
        sys.stderr.write(
            f"mellyn-guardrails: hook script not found: {{path}}. Run `pre-commit clean`, then retry.\\n"
        )
        sys.exit(1)
    sys.argv[0] = str(path)
    runpy.run_path(str(path), run_name="__main__")
    sys.exit(0)

{functions}'''


def _function_name(console_script: str) -> str:
    return console_script.removeprefix("mellyn-").replace("-", "_")


def _source_root() -> Path:
    """PEP 517 runs every hook with the source tree as the working directory."""
    root = Path.cwd().resolve()
    missing = [name for name in HOOKS.values() if not (root / "scripts" / name).is_file()]
    if missing or not (root / ".pre-commit-hooks.yaml").is_file():
        raise RuntimeError(f"mellyn_hook_backend: {root} is not a Mellyn Guardrails checkout (missing {missing})")
    return root


def _files(root: Path) -> dict[str, bytes]:
    dist_info = f"{NAME}-{VERSION}.dist-info"
    functions = "\n".join(
        f"\ndef {_function_name(cs)}() -> None:\n    _run({script!r})\n" for cs, script in HOOKS.items()
    )
    launcher = _LAUNCHER.format(scripts_dir=str(root / "scripts"), functions=functions)
    entry_points = "[console_scripts]\n" + "".join(f"{cs} = {NAME}:{_function_name(cs)}\n" for cs in HOOKS)
    metadata = (
        "Metadata-Version: 2.1\n"
        "Name: mellyn-guardrails-hooks\n"
        f"Version: {VERSION}\n"
        "Summary: Mellyn Guardrails pre-commit hook launchers\n"
        "License: Apache-2.0\n"
        "Requires-Python: >=3.12\n"
    )
    wheel = f"Wheel-Version: 1.0\nGenerator: mellyn_hook_backend\nRoot-Is-Purelib: true\nTag: {TAG}\n"
    return {
        f"{NAME}.py": launcher.encode("utf-8"),
        f"{dist_info}/METADATA": metadata.encode("utf-8"),
        f"{dist_info}/WHEEL": wheel.encode("utf-8"),
        f"{dist_info}/entry_points.txt": entry_points.encode("utf-8"),
    }


def _record_line(path: str, data: bytes) -> str:
    digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode("ascii")
    return f"{path},sha256={digest},{len(data)}\n"


def get_requires_for_build_wheel(config_settings: dict[str, object] | None = None) -> list[str]:
    return []


def build_wheel(
    wheel_directory: str,
    config_settings: dict[str, object] | None = None,
    metadata_directory: str | None = None,
) -> str:
    files = _files(_source_root())
    record_path = f"{NAME}-{VERSION}.dist-info/RECORD"
    record = "".join(_record_line(path, data) for path, data in files.items()) + f"{record_path},,\n"
    files[record_path] = record.encode("utf-8")

    filename = f"{NAME}-{VERSION}-{TAG}.whl"
    with zipfile.ZipFile(Path(wheel_directory) / filename, "w", compression=zipfile.ZIP_DEFLATED) as whl:
        for path, data in files.items():
            info = zipfile.ZipInfo(path, date_time=ZIP_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            whl.writestr(info, data)
    return filename


def build_sdist(sdist_directory: str, config_settings: dict[str, object] | None = None) -> str:
    raise RuntimeError("mellyn_hook_backend builds wheels for pre-commit only; it does not build an sdist.")
